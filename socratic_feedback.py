"""Score-to-Socratic feedback: turn an argument-quality assessment into guiding questions.

Flow: weak argument + assessment -> personalised Socratic question -> student answer ->
follow-up question (built from the answer and the conversation history) -> ... -> student
revises the argument -> reassessment and score comparison -> optional suggestions.

With an LLM engine, every question is generated by the model. With the heuristic demo engine,
questions come from templates filled with the student's own words (marked source='template').
"""
import re

import config
import heuristic_engine as heur
from feedback import compare_assessments, generate_suggestions
from predict import WEAKNESS_LABELS
from utils import now_iso, save_json, short_quote, timestamp, truncate_words

WEAKNESS_PRIORITY = ["unclear_claim", "missing_evidence", "weak_reasoning", "too_vague", "off_topic"]

WEAKNESS_GOALS = {
    "unclear_claim": "help the student say precisely what they mean (who, what, compared with what)",
    "missing_evidence": "help the student find a concrete example, fact or source",
    "weak_reasoning": "help the student explain the steps that connect their reason to their conclusion",
    "too_vague": "help the student make their evidence specific",
    "off_topic": "help the student connect the point back to the main question",
    "deepen": "help the student consider an objection and respond to it",
}

SOCRATIC_SYSTEM = (
    "You are a kind Socratic writing tutor talking to a student about ONE argument from their essay. "
    "Rules: ask exactly ONE short question (maximum 35 words). NEVER give the answer, NEVER rewrite or "
    "correct the student's argument, and NEVER give a list of tips. Refer to the student's own words. "
    "Be encouraging and easy to understand. Output only the question.")


def primary_weakness(assessment):
    types = assessment.get("weakness_types", [])
    for w in WEAKNESS_PRIORITY:
        if w in types:
            return w
    return "deepen"


def clean_question(raw):
    """Keep a single question from model output. Returns None if there is no question."""
    if not raw:
        return None
    text = raw.strip().strip('"').strip()
    text = re.sub(r"^(question|socratic question)\s*[:\-]\s*", "", text, flags=re.I)
    if "?" not in text:
        return None
    first = text.find("?")
    q = text[:first + 1].strip()
    # keep a short lead-in sentence if the model produced one before the question
    return q if len(q.split()) >= 3 else None


class SocraticSession:
    """One Socratic conversation about one weak argument."""

    def __init__(self, analyzer, essay_text, segment):
        if not segment.get("assessment"):
            raise ValueError("This argument has no assessment yet, so Socratic questions cannot be created.")
        self.analyzer = analyzer
        self.essay = essay_text
        self.segment_idx = segment["idx"]
        self.arg_type = segment["type"]
        self.original_text = segment["text"]
        self.original_assessment = segment["assessment"]
        self.current_text = self.original_text
        self.current_assessment = self.original_assessment
        self.weakness = primary_weakness(self.original_assessment)
        self.history = []          # {"role": "ai"|"student", "content", "source", "time"}
        self.revisions = []        # {"text", "assessment", "comparison", "time"}
        self.suggestion_result = None
        self.started = False

    # ------------------------------------------------------------------ helpers
    @property
    def student_replies(self):
        return [h for h in self.history if h["role"] == "student"]

    @property
    def rounds(self):
        return len(self.student_replies)

    @property
    def can_view_suggestions(self):
        """Suggestions unlock after the student has tried (answered a question or revised)."""
        return self.rounds >= 1 or len(self.revisions) >= 1

    @property
    def suggest_revision(self):
        return self.rounds >= config.SOCRATIC_ROUNDS_BEFORE_REVISION_HINT

    def _add(self, role, content, source):
        self.history.append({"role": role, "content": content, "source": source, "time": now_iso()})

    def _context_message(self):
        a = self.current_assessment
        return (f"Essay excerpt (context):\n\"\"\"{truncate_words(self.essay, 250)}\"\"\"\n\n"
                f"The argument ({self.arg_type}) the student wrote:\n\"\"\"{self.original_text}\"\"\"\n"
                f"Assessment summary: score {a['score']}/10. Weaknesses: "
                f"{'; '.join(a.get('weaknesses', [])) or 'none'}. Explanation: {a.get('explanation', '')}\n"
                f"Main weakness to explore: {WEAKNESS_LABELS.get(self.weakness, 'depth of argument')}.\n"
                f"Goal: {WEAKNESS_GOALS[self.weakness]}.\nAsk your first Socratic question.")

    def _llm_messages(self):
        msgs = [{"role": "system", "content": SOCRATIC_SYSTEM},
                {"role": "user", "content": self._context_message()}]
        for i, h in enumerate(self.history):
            if h["role"] == "ai":
                msgs.append({"role": "assistant", "content": h["content"]})
            else:
                is_last = i == len(self.history) - 1
                extra = (f"\n\n(Ask ONE follow-up question that builds on this answer and moves toward: "
                         f"{WEAKNESS_GOALS[self.weakness]}. Do not give the answer.)") if is_last else ""
                msgs.append({"role": "user", "content": f"Student's answer: {h['content']}{extra}"})
        return msgs

    # ------------------------------------------------------------------ conversation
    def start(self):
        """Create the first Socratic question. Safe to call once."""
        if self.started:
            return self.history[0]["content"]
        q, source = None, "template"
        if self.analyzer.is_llm:
            raw = self.analyzer.generate(self._llm_messages(), config.QUESTION_MAX_NEW_TOKENS, 0.4, False)
            q = clean_question(raw)
            source = "llm" if q else "template-fallback"
        if q is None:
            q = heur.first_question(self.original_text, self.weakness)
        self._add("ai", q, source)
        self.started = True
        return q

    def reply(self, answer):
        """Record the student's answer and return the AI's follow-up question."""
        if not self.started:
            raise ValueError("Start the session first.")
        answer = (answer or "").strip()
        if len(answer) < config.MIN_STUDENT_ANSWER_CHARS:
            raise ValueError("Please write an answer before sending.")
        if len(answer) > config.MAX_STUDENT_ANSWER_CHARS:
            raise ValueError(f"Please keep your answer under {config.MAX_STUDENT_ANSWER_CHARS} characters.")
        self._add("student", answer, "student")
        q, source = None, "template"
        if self.analyzer.is_llm:
            raw = self.analyzer.generate(self._llm_messages(), config.QUESTION_MAX_NEW_TOKENS, 0.4, False)
            q = clean_question(raw)
            source = "llm" if q else "template-fallback"
        if q is None:
            q = heur.followup_question(self.current_text, self.weakness, answer, self.rounds)
        self._add("ai", q, source)
        return q

    def revise(self, new_text):
        """Student submits an improved version. Reassess and compare with the previous version."""
        new_text = (new_text or "").strip()
        if len(new_text.split()) < 3:
            raise ValueError("Please write a revised argument (at least a few words).")
        if new_text == self.current_text.strip():
            raise ValueError("The revised text is identical to the current version. Try changing it first.")
        assessment = self.analyzer.assess_argument(new_text, self.arg_type, self.essay)
        comparison = compare_assessments(self.current_assessment, assessment)
        self.revisions.append({"text": new_text, "assessment": assessment,
                               "comparison": comparison, "time": now_iso()})
        self.current_text, self.current_assessment = new_text, assessment
        return self.revisions[-1]

    def get_suggestions(self):
        if not self.can_view_suggestions:
            raise PermissionError("Try answering a Socratic question or revising the argument first; "
                                  "then suggestions will unlock.")
        if self.suggestion_result is None:
            self.suggestion_result = generate_suggestions(
                self.analyzer, self.essay, self.current_text, self.arg_type, self.current_assessment)
        return self.suggestion_result

    # ------------------------------------------------------------------ summary / export
    def feedback_card(self):
        """Everything the requirements list: original argument, weakness, question, response, suggestion."""
        pairs, pending = [], None
        for h in self.history:
            if h["role"] == "ai":
                pending = {"question": h["content"], "question_source": h["source"], "student_response": None}
                pairs.append(pending)
            elif pending is not None:
                pending["student_response"] = h["content"]
        return {
            "original_argument": self.original_text,
            "argument_type": self.arg_type,
            "original_score": self.original_assessment["score"],
            "identified_weakness": WEAKNESS_LABELS.get(self.weakness, "Could be developed further"),
            "weakness_details": self.original_assessment.get("weaknesses", []),
            "exchanges": pairs,
            "revised_argument": self.current_text if self.revisions else None,
            "latest_score": self.current_assessment["score"],
            "suggested_improvement": (self.suggestion_result["suggestions"]
                                      if self.suggestion_result else "Locked until you try to improve the argument."),
        }

    def to_dict(self):
        return {"essay_excerpt": truncate_words(self.essay, 80), "segment_idx": self.segment_idx,
                "engine": self.analyzer.engine.name, "card": self.feedback_card(),
                "history": self.history, "revisions": self.revisions}

    def save(self):
        path = config.SESSIONS_DIR / f"session_{timestamp()}_seg{self.segment_idx}.json"
        return save_json(self.to_dict(), path)
